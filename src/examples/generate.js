// Generated practice sentences for ANY saved word.
//
// Path A (optional): user-configured OpenAI-compatible chat endpoint (key stored only locally).
// Path B (default):  client-side templates. The headword is classified from licensed
//   dictionary definition text (verb-like / adjective-like / noun-like / unknown); several
//   distinct sentence frames for that class get the actual word inserted, and every Chinese
//   sentence is then translated with the SAME real translator used by the reader.
//   English is never invented here: failed translations are returned as en:null.
//
// No bundled LLM key exists and none may be added.

export const GENERATED_SOURCE = 'generated';
export const GENERATED_LABEL = 'Generated practice sentences (templates + live translation)';
export const LLM_SOURCE = 'llm';
export const LLM_LABEL = 'Generated by your configured model endpoint';

const ADJ_WORDS = new Set(
  ('good bad big small large little long short tall high low new old young happy sad beautiful pretty ugly ' +
    'hot cold warm cool fast quick slow easy difficult hard busy free clean dirty bright dark heavy light ' +
    'rich poor strong weak full empty near far early late many few much expensive cheap red white black ' +
    'green blue yellow true false right wrong correct clear quiet noisy safe dangerous kind polite ' +
    'important interesting lonely tired hungry thirsty angry afraid deep shallow thick thin wide narrow ' +
    'fat sweet bitter sour spicy salty fresh ripe sharp soft smooth rough simple complex famous careful')
    .split(/\s+/)
);
const ADJ_SUFFIX = /(ful|ous|ive|able|ible|less)$/;

/**
 * Lightweight, transparent classification from dictionary definition text.
 * @param {string} definition e.g. "to study, learn" | "good, excellent; fine" | "book, letter, document"
 * @returns {{kind:'verb'|'adjective'|'noun'|'unknown', basis:string}}
 */
export function classifyHeadword(definition) {
  const def = String(definition || '').trim().toLowerCase();
  if (!def) return { kind: 'unknown', basis: 'no licensed definition available for this word' };
  const first = def.split(/[;,]/)[0].trim().replace(/^\(.*?\)\s*/, '');
  if (/^to\s+\w/.test(first)) return { kind: 'verb', basis: `definition starts with “to …” (“${first}”)` };
  const firstWord = first.replace(/^(very|quite|rather|be)\s+/, '').split(/\s+/)[0];
  if (/^(very|quite)\s/.test(first) || ADJ_WORDS.has(firstWord) || (first.split(/\s+/).length <= 2 && ADJ_SUFFIX.test(firstWord) && !/(tion|ment|ness|ity|ship|er|or|ist)$/.test(firstWord))) {
    return { kind: 'adjective', basis: `definition reads like a description (“${first}”)` };
  }
  return { kind: 'noun', basis: `definition reads like a thing or concept (“${first}”)` };
}

// Each frame: zh template with {w}, and a frame-derived usage note (no extra linguistic claims).
const FRAMES = {
  verb: [
    { zh: '我今天想{w}。', note: 'Uses the word as a verb after 想 (“want to”) in a first-person statement.' },
    { zh: '你明天会{w}吗？', note: 'Uses the word as a verb in a yes/no question with 会 … 吗.' },
    { zh: '我们一起{w}吧。', note: 'Uses the word as a verb in a suggestion with 一起 … 吧 (“let’s … together”).' },
    { zh: '他不喜欢{w}。', note: 'Uses the word as a verb after 喜欢 (“like to”), negated with 不.' },
    { zh: '她每天都{w}。', note: 'Uses the word as a verb for a daily habit with 每天都.' },
    { zh: '昨天我没有时间{w}。', note: 'Uses the word as a verb after 没有时间 (“no time to”), past context.' },
  ],
  adjective: [
    { zh: '今天很{w}。', note: 'Uses the word as a predicate adjective after 很.' },
    { zh: '这个地方非常{w}。', note: 'Uses the word to describe a place, intensified by 非常.' },
    { zh: '我觉得他不太{w}。', note: 'Uses the word as an adjective after 觉得 with 不太 (“not very”).' },
    { zh: '这本书{w}吗？', note: 'Uses the word as an adjective in a yes/no question with 吗.' },
    { zh: '天气越来越{w}了。', note: 'Uses the word with 越来越 … 了 (“more and more”).' },
    { zh: '我希望明天也这么{w}。', note: 'Uses the word as an adjective after 这么 (“this …”), expressing a wish.' },
  ],
  noun: [
    { zh: '我在找{w}。', note: 'Uses the word as a noun object of 找 (“look for”).' },
    { zh: '{w}在哪里？', note: 'Uses the word as a noun subject in a 在哪里 (“where is”) question.' },
    { zh: '关于{w}，你知道多少？', note: 'Uses the word as a noun after 关于 (“about”) as the topic.' },
    { zh: '我昨天跟朋友聊了{w}。', note: 'Uses the word as a noun object of 聊 (“chat about”), past action with 了.' },
    { zh: '这里没有{w}。', note: 'Uses the word as a noun after 没有 (“there is no”).' },
    { zh: '我很喜欢{w}。', note: 'Uses the word as a noun object of 喜欢 (“like”).' },
  ],
  unknown: [
    { zh: '我今天学了“{w}”这个词。', note: 'Mentions the word itself (“the word …”); no part of speech assumed.' },
    { zh: '你知道“{w}”是什么意思吗？', note: 'Asks about the meaning of the word; no part of speech assumed.' },
    { zh: '老师用“{w}”造了一个句子。', note: 'Talks about making a sentence with the word; no part of speech assumed.' },
    { zh: '这本书里有“{w}”这个词。', note: 'States that the word appears in a book; no part of speech assumed.' },
  ],
};

/** Frames that work for any word (always mixed in). */
const GENERIC = [
  { zh: '“{w}”这个词怎么用？', note: 'Meta-question about how to use the word; works for any part of speech.' },
  { zh: '请用“{w}”说一句话。', note: 'Request to say a sentence with the word (polite 请); works for any part of speech.' },
];

/** Deterministic pick so the same word gets varied but stable frames. */
function pickFrames(list, n, seed) {
  const out = [];
  const used = new Set();
  let h = 0;
  for (const ch of seed) h = (h * 31 + ch.codePointAt(0)) >>> 0;
  for (let k = 0; out.length < Math.min(n, list.length); k++) {
    const idx = (h + k * 7) % list.length;
    if (!used.has(idx)) {
      used.add(idx);
      out.push(list[idx]);
    }
    if (k > list.length * 8) break;
  }
  return out;
}

/** Build template sentences (Chinese + note) without translation. */
export function buildTemplateSentences(word, definition, count = 5) {
  const cls = classifyHeadword(definition);
  const main = pickFrames(FRAMES[cls.kind], Math.max(3, count - 1), word);
  const generic = pickFrames(GENERIC, 1, word);
  const frames = [...main, ...generic].slice(0, Math.max(4, count));
  const defNote = definition ? ` Dictionary: “${String(definition).split(';')[0].trim()}”.` : '';
  return {
    classification: cls,
    sentences: frames.map((f) => ({
      zh: f.zh.replaceAll('{w}', word),
      note: `${f.note}${f === generic[0] ? '' : defNote}`,
      frame: f.zh,
    })),
  };
}

/**
 * Call an OpenAI-compatible chat endpoint configured by the user.
 * @returns {Promise<{zh:string,en:string|null,note:string}[]>}
 */
export async function generateWithEndpoint(word, definition, { endpoint, apiKey, model, fetch: f = globalThis.fetch, signal }) {
  const prompt =
    `Write 5 natural, different Simplified Chinese example sentences that use the word “${word}”` +
    (definition ? ` (meaning: ${definition})` : '') +
    '. Return ONLY a JSON array of objects with keys "zh" (Chinese sentence), "en" (English translation) and "note" (a short usage note about register or grammar).';
  const headers = { 'Content-Type': 'application/json' };
  if (apiKey) headers.Authorization = `Bearer ${apiKey}`;
  const res = await f(endpoint, {
    method: 'POST',
    headers,
    signal,
    body: JSON.stringify({ model: model || 'gpt-4o-mini', messages: [{ role: 'user', content: prompt }], temperature: 0.7 }),
  });
  if (!res.ok) throw new Error(`Endpoint HTTP ${res.status}`);
  const json = await res.json();
  const content = json?.choices?.[0]?.message?.content ?? json?.content ?? '';
  const m = String(content).match(/\[[\s\S]*\]/);
  if (!m) throw new Error('Endpoint reply did not contain a JSON array');
  const arr = JSON.parse(m[0]);
  return arr
    .filter((x) => x && typeof x.zh === 'string' && x.zh.includes(word))
    .map((x) => ({ zh: x.zh.trim(), en: typeof x.en === 'string' ? x.en.trim() : null, note: String(x.note || '').trim() }));
}

/**
 * Generate 4+ practice sentences for a word.
 * @param {string} word
 * @param {{definition?:string, translate:(zh:string)=>Promise<{ok:boolean,en?:string}>, settings?:{genEndpoint?:string,genApiKey?:string,genModel?:string}, fetch?:Function, signal?:AbortSignal, onProgress?:(done:number,total:number)=>void}} opts
 * @returns {Promise<{source:string, label:string, classification?:object, examples:{zh:string,en:string|null,note:string,source:string,sourceLabel:string,translationProvider?:string}[], warning?:string}>}
 */
export async function generateExamples(word, opts) {
  const { definition = '', translate, settings = {}, signal, onProgress } = opts;
  let warning;
  if (settings.genEndpoint) {
    try {
      const list = await generateWithEndpoint(word, definition, {
        endpoint: settings.genEndpoint,
        apiKey: settings.genApiKey,
        model: settings.genModel,
        fetch: opts.fetch,
        signal,
      });
      if (list.length) {
        return {
          source: LLM_SOURCE,
          label: LLM_LABEL,
          examples: list.map((x) => ({ ...x, source: LLM_SOURCE, sourceLabel: LLM_LABEL })),
        };
      }
      warning = 'Your endpoint returned no usable sentences; fell back to templates.';
    } catch (e) {
      warning = `Your generation endpoint failed (${e.message}); fell back to templates.`;
    }
  }
  const { classification, sentences } = buildTemplateSentences(word, definition);
  const examples = [];
  let i = 0;
  for (const s of sentences) {
    if (signal?.aborted) break;
    const tr = await translate(s.zh);
    examples.push({
      zh: s.zh,
      en: tr && tr.ok ? tr.en : null,
      translationProvider: tr && tr.ok ? tr.provider : undefined,
      translationError: tr && !tr.ok ? tr.error || 'translation unavailable' : undefined,
      note: s.note,
      source: GENERATED_SOURCE,
      sourceLabel: GENERATED_LABEL,
    });
    onProgress?.(++i, sentences.length);
  }
  return { source: GENERATED_SOURCE, label: GENERATED_LABEL, classification, examples, warning };
}

/** Human label for a saved example's source. */
export function sourceLabel(source) {
  if (source === 'tatoeba') return 'Tatoeba (CC-BY)';
  if (source === GENERATED_SOURCE) return 'Generated (template + live translation)';
  if (source === LLM_SOURCE) return 'Generated (your model endpoint)';
  if (source === 'context') return 'From your reading';
  return source || 'Unknown';
}
